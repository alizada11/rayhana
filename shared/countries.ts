export type CountryCode = (typeof COUNTRIES)[number][0];
export type CountryLocale = "fa" | "en" | "ps";

export const COUNTRIES_EN = COUNTRIES.map(([code, , label]) => [code, label] as const);
export const COUNTRIES_PS = COUNTRIES.map(([code, , , label]) => [code, label] as const);
export const COUNTRY_CODES = COUNTRIES.map(([code]) => code) as CountryCode[];
export const COUNTRY_LABELS = Object.fromEntries(COUNTRIES.map(([code, label]) => [code, label]));
export const COUNTRY_LABELS_EN = Object.fromEntries(COUNTRIES_EN);
export const COUNTRY_LABELS_PS = Object.fromEntries(COUNTRIES_PS);
export const COUNTRY_LABELS_BY_LOCALE = { fa: COUNTRY_LABELS, en: COUNTRY_LABELS_EN, ps: COUNTRY_LABELS_PS } as const;

export function getCountryLabel(code: string, locale: CountryLocale = "fa") {
  return COUNTRY_LABELS_BY_LOCALE[locale][code as CountryCode] ?? code;
}
